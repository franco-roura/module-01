export type CategoryIconName = keyof typeof categoryIcons;

export function categoryIcon(name: string): LucideIcon {
  return (categoryIcons as Record<string, LucideIcon>)[name] ?? CircleHelp;
}

/** Category/label palette token names (see tokens.json `cat-*`). */
export const categoryColors = [
  "cat-red",
  "cat-orange",
  "cat-amber",
  "cat-yellow",
  "cat-lime",
  "cat-green",
  "cat-teal",
  "cat-cyan",
  "cat-sky",
  "cat-blue",
  "cat-indigo",
  "cat-violet",
  "cat-pink",
  "cat-rose",
  "cat-brown",
  "cat-slate",
] as const;

export type CategoryColor = (typeof categoryColors)[number];

/** CSS color for a palette token name; unknown names fall back to slate. */
export function categoryColorVar(color: string): string {
  const known = (categoryColors as readonly string[]).includes(color) ? color : "cat-slate";
  return `var(--color-${known})`;
}
