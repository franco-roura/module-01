import { Button, HudLabel, Panel, SectionHeader } from "@franco_roura/module-01";
import type * as React from "react";
import { CodeBlock } from "../components/code-block";
import { data } from "../data";
import { entries } from "../registry";
import { Link } from "../router";

function Step({
  code,
  title,
  children,
}: {
  code: string;
  title: string;
  children: React.ReactNode;
}) {
  return (
    <section className="flex flex-col gap-4">
      <HudLabel code={code}>{title}</HudLabel>
      <div className="flex max-w-[70ch] flex-col gap-4">{children}</div>
    </section>
  );
}

const Code = ({ children }: { children: React.ReactNode }) => (
  <code className="rounded-xs bg-shell-recess px-1.5 py-px font-mono text-[0.85em]">
    {children}
  </code>
);

export function GettingStartedPage() {
  const name = data.name;
  return (
    <div className="flex flex-col gap-12">
      <SectionHeader code="S-01" label="Setup" title="Get started" ruler />

      <Step code="01" title="Install">
        <p>
          The package needs React 19. Everything else it uses (Radix, Lucide, cmdk) comes with it.
        </p>
        <CodeBlock code={`bun add ${name}\n# or\nnpm install ${name}`} />
      </Step>

      <Step code="02" title="Add the styles">
        <p>
          With <strong>Tailwind v4</strong>, import the theme after Tailwind in your global
          stylesheet. It registers the tokens as utilities (<Code>bg-shell</Code>,{" "}
          <Code>text-ink-soft</Code>, <Code>notch-md</Code>, <Code>hud</Code>) and points Tailwind
          at the kit's files, so its classes are generated by your own build, into the same
          stylesheet as your app's. All of the kit's styles come to about 14 kB gzipped.
        </p>
        <CodeBlock title="APP.CSS" code={`@import "tailwindcss";\n@import "${name}/theme.css";`} />
        <p>
          <strong>Without Tailwind</strong>, import the precompiled stylesheet once at your app's
          root. It carries every component's styles and the tokens as custom properties.
        </p>
        <CodeBlock title="MAIN.TSX" code={`import "${name}/styles.css";`} />
        <p>
          Only want the tokens? <Code>{`${name}/tokens.css`}</Code> has them as plain custom
          properties, and <Code>{`${name}/tokens.json`}</Code> is the source with a usage note for
          each.
        </p>
      </Step>

      <Step code="03" title="Load the fonts">
        <p>
          Module/01 sets display type in Michroma, text in Manrope and HUD markings in Space Mono.
          The package doesn't bundle them, so load them however your app loads fonts. From Google
          Fonts:
        </p>
        <CodeBlock
          title="INDEX.HTML"
          code={`<link rel="preconnect" href="https://fonts.googleapis.com" />\n<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin />\n<link\n  rel="stylesheet"\n  href="https://fonts.googleapis.com/css2?family=Manrope:wght@400;600;700&family=Michroma&family=Space+Mono:wght@400;700&display=swap"\n/>`}
        />
        <p>
          With <Code>next/font</Code> or a self-hosted file, expose each family through the variable
          the font stacks look for first: <Code>--font-michroma</Code>, <Code>--font-manrope</Code>{" "}
          and <Code>--font-space-mono</Code>.
        </p>
        <CodeBlock
          title="APP/LAYOUT.TSX"
          code={`import { Manrope, Michroma, Space_Mono } from "next/font/google";\n\nconst michroma = Michroma({ weight: "400", subsets: ["latin"], variable: "--font-michroma" });\nconst manrope = Manrope({ subsets: ["latin"], variable: "--font-manrope" });\nconst spaceMono = Space_Mono({ weight: ["400", "700"], subsets: ["latin"], variable: "--font-space-mono" });\n\n// <html className={\`\${michroma.variable} \${manrope.variable} \${spaceMono.variable}\`}>`}
        />
      </Step>

      <Step code="04" title="Use a component">
        <CodeBlock
          code={`import { Button, Field, Input, Panel, SectionHeader } from "${name}";\n\nexport function NewWallet() {\n  return (\n    <Panel serial="W-01 · NEW" cross>\n      <SectionHeader as="h2" code="S-01" label="Wallets" title="Add wallet" />\n      <Field label="Name" htmlFor="wallet-name">\n        <Input id="wallet-name" placeholder="Savings" />\n      </Field>\n      <Button arrow>Save</Button>\n    </Panel>\n  );\n}`}
        />
        <p>
          Mount <Code>{"<Toaster />"}</Code> and <Code>{"<TooltipProvider>"}</Code> once at the root
          if you use toasts or tooltips.
        </p>
      </Step>

      <Step code="05" title="Pick your entry points">
        <p>
          The kit is split so that heavy dependencies stay out of apps that don't need them. Every
          entry is tree-shakable: importing <Code>Button</Code> doesn't pull in the calendar.
        </p>
        <div className="grid gap-4 sm:grid-cols-2">
          {Object.values(entries).map((entry) => (
            <Panel key={entry.importPath} notch="sm" bodyClassName="p-5 sm:p-5">
              <p className="hud-sm text-ink-soft">{entry.title}</p>
              <p className="mt-1 font-mono text-body-sm break-all">{entry.importPath}</p>
            </Panel>
          ))}
        </div>
        <p>
          <Code>/charts</Code> needs Recharts, an optional peer dependency:{" "}
          <Code>bun add recharts</Code>.
        </p>
      </Step>

      <Step code="06" title="Server components">
        <p>
          Interactive components are marked <Code>"use client"</Code> in the published files, so you
          can import them straight into a React Server Component. Static parts (Panel, the HUD
          markings, Button, Badge) render on the server.
        </p>
      </Step>

      <div className="flex flex-wrap gap-3">
        <Button asChild>
          <Link to="/components">
            Browse the components
            <span aria-hidden className="font-mono">
              →
            </span>
          </Link>
        </Button>
        <Button variant="secondary" asChild>
          <Link to="/tokens">See the tokens</Link>
        </Button>
      </div>
    </div>
  );
}
